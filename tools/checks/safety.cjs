/* 민감 주제 검사 (집필가이드 "민감한 주제", "응급 태그")
   오류: 응급 태그 글에 119 없음 / "극단적 선택" 같은 말(본문·제목·요약)
   경고: 응급 태그 글에 warn 콜아웃 없음 / 자살·자해가 본문에 3번 이상인데 위기 태그 없음
   그리고 "스스로 끊어도 된다"는 뜻의 말(한계선 2)을 잡는 정규식 한 벌(stopAdviceRe)을 여기서 만들어 내보내요.
   본문 금지 표현 '임의 중단 권유'(tools/check-content.cjs)와 약 카드의 넣지 않는 말 '끊어도 된다는 말'
   (tools/checks/drug-card.cjs, 생성기 tools/gen/meds.cjs 도 같은 것)이 이것을 가져다 써요. */
'use strict';

/* 약을 가리키는 목적어와, 목적어와 동사 사이에 올 수 있는 짧은 꾸밈말("약을 한두 번 빼먹어도", "복용을 잠시 멈춰도", "약은 하루쯤 걸러도") */
const STOP_OBJ = '(?:약|약물|복용|투약|복약|주사|용량|복용량)(?:을|를|은|는|도)?\\s*';
const STOP_ADV = '(?:(?:(?:한두|한|두|몇)\\s*(?:번|차례)|하루|이틀|며칠|가끔|잠시|잠깐|당분간|조금|좀|이제|그냥|한동안)(?:쯤|정도|씩|은|는)?\\s*){0,2}';
/* 다른 목적어와 동사 사이에 올 수 있는 꾸밈말 하나. 아무 낱말이나 두지 않아요("저녁 약은 안 먹어도"의 "약은"을 건너뛰지 않게) */
const LITTLE_ADV = '(?:(?:굳이|꼭|억지로|잠시|잠깐|당분간|한동안|아예|완전히|조금씩|오늘은|이제|하루쯤|그냥)\\s*)?';
/* 약이 아닌 것을 끊는 이야기(담배·술·연락·관계·SNS·읽기 …) — 본문에서는 그 목적어가 바로 앞(사이에 꾸밈말 하나까지)에 있으면 빼요 */
const OTHER_OBJ = '(?<!(?:담배|흡연|술|음주|카페인|커피|연락|관계|인연|SNS|sns|인터넷|게임|읽기|운동|모임|만남|대화|뉴스|단톡방|알림)(?:을|를|은|는|도|과|와)?\\s*' + LITTLE_ADV + ')';
/* 밥·식사·술 이야기("밥을 먹지 않아도 돼요", "술은 안 드셔도 괜찮아요", "억지로 먹지 않아도 돼요") — 본문에서는 빼요 */
const FOOD_OBJ = '(?<!(?:밥|아침|점심|저녁|식사|간식|야식|끼니|음식|과자|술|커피|억지로)(?:을|를|은|는|도|이|가)?\\s*' + LITTLE_ADV + ')';

/* 끊는 동작 + "도". 앞에 무엇이 와도 잡는 꼴(높임말 포함). "안 끊어도·못 끊어도"(끊지 않아도 된다는 뜻)는 빼요.
   scope 마다 조금 달라요: 본문은 다른 목적어(담배·연락 …, 밥·술 …)가 앞에 있으면 빼고, 약 카드 칸은 약 이야기뿐이라 빼지 않아요 */
function stopVerbs(body) {
  const other = body ? OTHER_OBJ : '', food = body ? FOOD_OBJ : '';
  return [
    other + '(?<!안\\s?)(?<!못\\s?)끊(?:어|으셔)',
    '그만\\s*(?:먹어|먹으셔|드셔|복용해|복용하셔|투약해)',
    other + '중단(?:해|하셔)',
    food + '안\\s*(?:먹어|먹으셔|드셔|복용해|복용하셔)',
    food + '(?:먹지|드시지|복용하지|복용을?\\s*하지)\\s*않(?:아|으셔)',
    '약\\s*없이\\s*(?:지내|살아|버텨|견뎌|생활해)',
    /* 줄여도·빼도·멈춰도·쉬어도·건너뛰어도·빼먹어도·걸러도·중지해도·안 맞아도는 다른 이야기("잠시 멈춰도 괜찮아요", "일정에서 빼도",
       "운동을 하루쯤 빼먹어도", "아침을 걸러도", "모임은 중지해도", "옷이 안 맞아도")에도 쓰여서 본문은 약·복용·주사·용량을 가리킬 때만 */
    STOP_OBJ + STOP_ADV + '(?:줄여|줄이셔|빼|빼셔|멈춰|멈추셔|쉬어|쉬셔|그만둬|그만두셔|건너뛰어|건너뛰셔|빼먹어|빼먹으셔|걸러|거르셔|중지해|중지하셔|안\\s*맞아|안\\s*맞으셔|맞지\\s*않(?:아|으셔))'
  ];
}
const STOP_VERBS = stopVerbs(true);
/* 약 카드 칸은 약 이야기뿐이라 목적어 없이도 잡는 꼴 */
const STOP_VERBS_CARD = ['줄여', '줄이셔', '빼', '빼셔', '그만\\s*둬', '그만두셔', '멈춰', '멈추셔', '건너뛰어', '건너뛰셔', '쉬어', '쉬셔',
  '빼먹(?:어|으셔)', '(?<![가-힣])걸러', '거르셔', '중지(?:해|하셔)', '안\\s*맞(?:아|으셔)', '맞지\\s*않(?:아|으셔)'];
/* 동사 뒤에 붙는 보조 동사("끊어 봐도", "끊어 버려도") */
const STOP_AUX = '(?:\\s*(?:봐|보셔|버려|버리셔))?';
/* "약을 끊는 것도 괜찮아요·방법이에요". "담배를 끊는 것도 좋아요" 같은 다른 이야기와 나누려고 본문은 약·복용·주사가 앞에 있을 때만, 칸에서는 목적어 없이도 */
const STOP_THING_OBJ = '(?:약|약물|복용|투약|주사)(?:을|를)?\\s*';
const STOP_THING = '(?:끊|중단하|중지하|그만\\s*(?:먹|드시|복용하))는\\s*(?:것|게)도\\s*';
const STOP_THING_END = '(?:방법이에요|방법입니다|방법이다|방법이야)';
/* 끊으라는 명령꼴("약을 끊으세요", "복용을 중단하세요", "약은 그만 드세요"). 본문은 약·복용·주사가 앞에 있을 때만, 칸에서는 목적어 없이도 */
const STOP_CMD = '(?:끊으세요|끊으십시오|중단하세요|중단하십시오|중지하세요|그만\\s*(?:드세요|드시세요|먹으세요|복용하세요|맞으세요))(?!\\s*지\\s*말)';
/* 괜찮다고 끝맺는 말. "되는지·될까요·괜찮을까요·되지"처럼 묻거나 부정하는 꼴은 여기에 없어서 걸리지 않아요.
   흔한 맞춤법 "되요", 추측·완곡("될 거예요·되겠죠·괜찮을 거예요·문제없어요·되더라고요")도 같은 뜻이라 잡아요 */
const STOP_END = '(?:돼요|돼(?![가-힣])|되요|됩니다|된다|되어요|괜찮아요|괜찮아(?![가-힣])|괜찮습니다|괜찮다|좋아요|좋습니다|좋다' +
  '|무방해요|무방합니다|무방하다|상관없어요|상관없습니다|상관없다|문제없어요|문제없습니다|문제없다' +
  '|될\\s*(?:거예요|거에요|겁니다|거야|듯해요|듯합니다|것\\s*같아요|것\\s*같습니다)|되겠죠|되겠어요|되겠습니다' +
  '|괜찮을\\s*(?:거예요|거에요|겁니다|거야)|되더라(?:고요)?|괜찮더라(?:고요)?)';
const QUOTE = '[\'"‘’“”「」『』]';
/* 빼는 꼴: 묻는 꼴(…돼요?), 그 말을 옮기거나 부정하는 꼴("…된다"는, 된다고, 된다면, "…돼요."라고, '…돼' 하는, "…돼요, 라는 말"),
   따옴표로 옮긴 뒤 40자 안에 그 말을 바로잡는 말이 오는 꼴("…돼요." 많이 하는 오해예요, "…괜찮아요." 이런 글은 믿지 말아요,
   "…돼요." 이런 말은 근거가 없어요). 바로잡는 말은 좁게만 둬요 — "걱정하지 마세요·잘 생기지 않아요·위험하지 않아요"처럼
   그 말을 거드는 데도 흔한 말은 넣지 않아요 */
const STOP_FIX = '(?:오해|통념|착각|사실이\\s*아니|사실과\\s*달|틀린|틀려|틀렸|잘못된|잘못\\s*알려|근거가?\\s*없|믿지\\s*말|따르지\\s*말|그렇지\\s*않)';
const STOP_NOT =
  '(?![가-힣]*\\?)' +
  '(?!(?:[.!…~]*' + QUOTE + '|' + QUOTE + '?)\\s*(?:는|고|며|라|란|면|와|과|처럼|거나|니|든지|던|하(?:는|고|며|면|기|던)))' +
  '(?![.!…~]*' + QUOTE + '?\\s*,\\s*(?:라는|란|라고|하는))' +
  '(?![.!…~]*' + QUOTE + '[^\\n]{0,40}?' + STOP_FIX + ')';

/* scope: 'body'(본문·핵심 3가지·용어 정의) 또는 'card'(약 카드 칸) → 새 RegExp */
function stopAdviceRe(scope) {
  const card = scope === 'card';
  const verbs = card ? stopVerbs(false).concat(STOP_VERBS_CARD) : STOP_VERBS;
  const obj = card ? '(?:' + STOP_THING_OBJ + ')?' : STOP_THING_OBJ;
  const cmdObj = card ? '(?:' + STOP_OBJ + STOP_ADV + ')?' : STOP_OBJ + STOP_ADV;
  return new RegExp('(?:(?:(?:' + verbs.join('|') + ')' + STOP_AUX + '도\\s*|' + obj + STOP_THING + ')' +
    '(?:' + STOP_END + '|' + STOP_THING_END + ')|' + cmdObj + STOP_CMD + ')' + STOP_NOT);
}

module.exports = {
  id: 'safety',
  STOP_VERBS: STOP_VERBS, STOP_VERBS_CARD: STOP_VERBS_CARD, STOP_END: STOP_END, STOP_NOT: STOP_NOT, STOP_FIX: STOP_FIX, STOP_CMD: STOP_CMD, stopAdviceRe: stopAdviceRe,
  check: function (ctx, report) {
    const tags = ctx.tags, body = ctx.body, m = ctx.meta;

    if (tags.indexOf('응급') >= 0) {
      if (!/(^|[^\d])119(?!\d)/.test(body)) report.error('응급 태그 글인데 본문에 119 없음');
      if (!/^:::\s*warn\b/m.test(body)) report.warn('응급 태그 글인데 "바로 연락할 신호" warn 콜아웃이 없음');
    }

    [['본문', body], ['제목', m.title], ['요약', m.summary]].forEach(function (w) {
      const hit = ctx.EXTREME_CHOICE.exec(String(w[1] || ''));
      if (hit) report.error(w[0] + '에 "' + hit[0] + '" — 자살을 에두르는 말은 쓰지 않아요(자살예방 보도준칙). "자살"로 쓰고 도움 경로를 함께');
    });

    /* 기관·전화·법 이름(자살예방상담, 자살예방센터, 자살예방법 등)은 세지 않는다 */
    const n = (body.replace(/자살\s*예방\s*(?:상담\s*전화|상담|센터|법|정책|사업)?/g, '').match(/자살|자해/g) || []).length;
    if (n >= 3 && tags.indexOf('위기') < 0) {
      report.warn('본문에 "자살·자해"가 ' + n + '번 — 한 소절 이상 다루면 위기 태그와 109·1577-0199·119');
    }
  }
};
